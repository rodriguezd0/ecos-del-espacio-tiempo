export const GLYPH_W = 6; // 5 px + 1 de espacio
export const GLYPH_H = 8;

/** Ancho en píxeles de un texto a escala 1. */
export const textWidth = (text) => String(text).length * GLYPH_W;

function setPixel(png, x, y, rgba) {
  if (x < 0 || y < 0 || x >= png.width || y >= png.height) return;
  const i = (y * png.width + x) * 4;
  png.data[i] = rgba[0]; png.data[i + 1] = rgba[1]; png.data[i + 2] = rgba[2]; png.data[i + 3] = 255;
}

/** Rellena un rectángulo opaco. */
export function fillRect(png, x, y, w, h, rgba) {
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) setPixel(png, x + i, y + j, rgba);
}

/** Dibuja texto (fuente 5×7) en (x,y); `bg` opcional dibuja una caja detrás. */
export function drawText(png, x, y, text, rgba = [255, 255, 255, 255], bg = null) {
  const str = String(text);
  if (bg) fillRect(png, x - 1, y - 1, textWidth(str) + 1, GLYPH_H + 1, bg);
  for (let n = 0; n < str.length; n++) {
    const ch = str[n];
    const g = GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || GLYPHS['?'];
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < 5; c++) if (g[r][c] === '1') setPixel(png, x + n * GLYPH_W + c, y + r, rgba);
    }
  }
}
